export function defaultLessonContentSections(
  description: string,
): StudentLessonContentSections {
  const d = description.trim() || "эту тему";
  return {
    aboutLesson: `В этом уроке вы последовательно разберёте: ${d}. Материал выстроен от интуитивных примеров к более общим выводам, чтобы проще переносить идеи на новые ситуации.`,
    learningOutcomes: `После прохождения вы сможете своими словами объяснить ключевые понятия, связанные с «${d}», заметите типичные заблуждения и поймёте, как эта тема сочетается с остальным курсом.`,
    aiConnection: `Связь с обучением ИИ: вы увидите, как описанные идеи входят в цикл данных → модель → обучение → оценка качества, и зачем аккуратность на каждом шаге влияет на надёжность системы в реальных задачах.`,
    practice: `Практическая часть урока закрепляет теорию через задания ниже: выполняйте их последовательно и возвращайтесь к тексту разделов, если формулировка вопроса кажется незнакомой.`,
  };
}

export function lessonContentSectionsForSnapshot(
  title: string,
  description: string,
): StudentLessonContentSections {
  return KNOWN[title] ?? defaultLessonContentSections(description);
}

/** Plaintext fallback for consumers that only read `content`. */
export function lessonLegacyContentFromSections(
  description: string,
  sections: StudentLessonContentSections,
): string {
  return [
    description,
    `О чём этот урок\n${sections.aboutLesson}`,
    `Что поймёт ученик\n${sections.learningOutcomes}`,
    `Как это связано с обучением ИИ\n${sections.aiConnection}`,
    `Практика\n${sections.practice}`,
  ].join("\n\n");
}

export function buildLessonSnapshotContent(
  title: string,
  description: string,
): {
  contentSections: StudentLessonContentSections;
  content: string;
} {
  const contentSections = lessonContentSectionsForSnapshot(title, description);
  const content = lessonLegacyContentFromSections(description, contentSections);
  return { contentSections, content };
}
